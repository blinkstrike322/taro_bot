import { describe, it, expect } from 'vitest';
import { splitParagraphs, joinedParagraphs } from '../../lib/prose';

// «Трейл» — длинный хвост БЕЗ знаков препинания: попадает в авторазбивку
// (текст длиннее LONG_ENOUGH=260), но сам не дробится, поэтому схема детерминирована.
const trail = ' очень-длинный-продолжительный-придаточный-оборот-который-увеличивает-длину-без-знаков';
const longEnough = (s: string): string => s + trail.repeat(6);

describe('prose / splitParagraphs (Safari-15-безопасно, без lookbehind)', () => {
  it('дробит длинный сплошной текст по предложениям и группирует по 2', () => {
    const paras = splitParagraphs(
      longEnough('Первое предложение. Второе предложение. Третье предложение. Четвёртое предложение.'),
    );
    expect(paras[0]).toBe('Первое предложение. Второе предложение.');
    expect(paras[1]).toBe('Третье предложение. Четвёртое предложение.');
    // третий абзац = хвост без знаков (не дробится)
    expect(paras.length).toBe(3);
    expect(paras[2]).toContain('очень-длинный');
  });

  it('не рвёт число с точкой 3.5', () => {
    const paras = splitParagraphs(
      longEnough('Всего 3.5 метра хватит с запасом. Но лучше проверить заранее ещё раз.'),
    );
    expect(paras[0]).toBe('Всего 3.5 метра хватит с запасом. Но лучше проверить заранее ещё раз.');
  });

  it('сохраняет многоточие и двойные знаки примыкающими к предложению', () => {
    const paras = splitParagraphs(
      longEnough('Тени тянутся в распадок… это знак неверный. И вот что?! Слежу дальше внимательно.'),
    );
    const j = paras.join('\n\n');
    expect(j).toContain('…');
    expect(j).toContain('?!');
    // '...' и '?!' не покидают последнюю знаковую группу (стоят со своим предложением),
    // т.е. никогда не встречаются оторванными от текста на границе абзаца
    expect(j).not.toMatch(/…\n\n/);
    expect(j).not.toMatch(/\?\n\n/);
  });

  it('уважает уже имеющиеся переносы строк даже на коротком тексте', () => {
    expect(splitParagraphs('Первая строка\n\nВторая строка')).toEqual([
      'Первая строка',
      'Вторая строка',
    ]);
  });

  it('короткий сплошной текст без знаков — одним абзацем', () => {
    expect(splitParagraphs('короткий текст вообще весь')).toEqual(['короткий текст вообще весь']);
  });

  it('joinedParagraphs склеивает абзацы двойным переносом', () => {
    const j = joinedParagraphs(longEnough('Первый абз. Второй абз. Третий абз. Четвёртый абз.'));
    expect(j).toContain('\n\n');
    expect(j.split('\n\n').length).toBe(3);
  });
});